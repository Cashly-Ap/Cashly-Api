CREATE TABLE `cash_registers` (
  `id` binary(16) NOT NULL,
  `closure_date` date NOT NULL,
  `status` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'OPEN',
  `opened_by` binary(16) NOT NULL,
  `opened_by_name` varchar(255) COLLATE utf8mb4_unicode_ci NOT NULL,
  `opened_at` datetime NOT NULL,
  `opening_balance` decimal(15,2) NOT NULL DEFAULT '0.00',
  `closed_by` binary(16) DEFAULT NULL,
  `closed_by_name` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `closed_at` datetime DEFAULT NULL,
  `total_payments` decimal(15,2) NOT NULL DEFAULT '0.00',
  `total_advances` decimal(15,2) NOT NULL DEFAULT '0.00',
  `total_returns` decimal(15,2) NOT NULL DEFAULT '0.00',
  `total_credit_notes` decimal(15,2) NOT NULL DEFAULT '0.00',
  `total_debit_notes` decimal(15,2) NOT NULL DEFAULT '0.00',
  `total_invoices` decimal(15,2) NOT NULL DEFAULT '0.00',
  `payment_count` int NOT NULL DEFAULT '0',
  `advance_count` int NOT NULL DEFAULT '0',
  `return_count` int NOT NULL DEFAULT '0',
  `invoice_count` int NOT NULL DEFAULT '0',
  `expected_closing_balance` decimal(15,2) NOT NULL DEFAULT '0.00',
  `actual_closing_balance` decimal(15,2) DEFAULT NULL,
  `difference` decimal(15,2) DEFAULT NULL,
  `total_income` decimal(15,2) NOT NULL DEFAULT '0.00',
  `total_expense` decimal(15,2) NOT NULL DEFAULT '0.00',
  `closing_notes` text COLLATE utf8mb4_unicode_ci,
  `version` int NOT NULL DEFAULT '0',
  `open_slot` tinyint GENERATED ALWAYS AS ((case when (`status` = _utf8mb4'OPEN') then 1 else NULL end)) STORED,
  `created_at` datetime NOT NULL,
  `updated_at` datetime NOT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_cash_register_single_open` (`open_slot`),
  KEY `fk_register_opened_by` (`opened_by`),
  KEY `fk_register_closed_by` (`closed_by`),
  KEY `idx_closure_date` (`closure_date`),
  KEY `idx_status` (`status`),
  KEY `fk_cash_registers_company` (`company_id`),
  CONSTRAINT `fk_cash_registers_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_register_closed_by` FOREIGN KEY (`closed_by`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_register_opened_by` FOREIGN KEY (`opened_by`) REFERENCES `users` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `cash_register_details` (
  `id` binary(16) NOT NULL,
  `closure_id` binary(16) NOT NULL,
  `payment_method_id` binary(16) DEFAULT NULL,
  `payment_method_name` varchar(255) COLLATE utf8mb4_unicode_ci NOT NULL,
  `transaction_count` int NOT NULL DEFAULT '0',
  `expected_amount` decimal(15,2) NOT NULL DEFAULT '0.00',
  `actual_amount` decimal(15,2) DEFAULT NULL,
  `difference` decimal(15,2) DEFAULT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  KEY `fk_detail_payment_method` (`payment_method_id`),
  KEY `idx_detail_closure_id` (`closure_id`),
  KEY `fk_cash_register_details_company` (`company_id`),
  CONSTRAINT `fk_cash_register_details_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_detail_payment_method` FOREIGN KEY (`payment_method_id`) REFERENCES `payment_methods` (`id`),
  CONSTRAINT `fk_detail_register` FOREIGN KEY (`closure_id`) REFERENCES `cash_registers` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
