CREATE TABLE `warehouses` (
  `id` binary(16) NOT NULL,
  `code` varchar(50) NOT NULL,
  `name` varchar(100) NOT NULL,
  `address` text NOT NULL,
  `state` varchar(100) DEFAULT NULL,
  `municipality` varchar(100) DEFAULT NULL,
  `postal_code` varchar(10) DEFAULT NULL,
  `active` tinyint(1) NOT NULL DEFAULT '1',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  UNIQUE KEY `code` (`code`),
  KEY `idx_warehouse_code` (`code`),
  KEY `idx_warehouse_name` (`name`),
  KEY `idx_warehouse_active` (`active`),
  KEY `fk_warehouses_company` (`company_id`),
  CONSTRAINT `fk_warehouses_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `warehouse_stock` (
  `id` binary(16) NOT NULL,
  `warehouse_id` binary(16) NOT NULL,
  `product_id` binary(16) NOT NULL,
  `quantity` int NOT NULL DEFAULT '0',
  `reserved` int NOT NULL DEFAULT '0',
  `last_movement_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_warehouse_product` (`warehouse_id`,`product_id`),
  KEY `idx_ws_warehouse` (`warehouse_id`),
  KEY `idx_ws_product` (`product_id`),
  KEY `idx_ws_reserved` (`reserved`),
  KEY `fk_warehouse_stock_company` (`company_id`),
  CONSTRAINT `fk_warehouse_stock_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_ws_product` FOREIGN KEY (`product_id`) REFERENCES `products` (`id`),
  CONSTRAINT `fk_ws_warehouse` FOREIGN KEY (`warehouse_id`) REFERENCES `warehouses` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `stock_movements` (
  `id` binary(16) NOT NULL,
  `warehouse_id` binary(16) NOT NULL,
  `product_id` binary(16) NOT NULL,
  `movement_type` varchar(30) NOT NULL,
  `quantity` int NOT NULL,
  `previous_stock` int NOT NULL,
  `new_stock` int NOT NULL,
  `origin_movement_id` binary(16) DEFAULT NULL,
  `transfer_batch_id` varchar(50) DEFAULT NULL,
  `reference_type` varchar(20) DEFAULT NULL,
  `reference_id` binary(16) DEFAULT NULL,
  `reference_number` varchar(100) DEFAULT NULL,
  `notes` varchar(500) DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  KEY `idx_sm_warehouse` (`warehouse_id`),
  KEY `idx_sm_product` (`product_id`),
  KEY `idx_sm_type` (`movement_type`),
  KEY `idx_sm_origin` (`origin_movement_id`),
  KEY `idx_sm_transfer_batch` (`transfer_batch_id`),
  KEY `idx_sm_created` (`created_at`),
  KEY `idx_sm_warehouse_product` (`warehouse_id`,`product_id`),
  KEY `idx_sm_ref_type_id` (`reference_type`,`reference_id`),
  KEY `fk_stock_movements_company` (`company_id`),
  CONSTRAINT `fk_sm_product` FOREIGN KEY (`product_id`) REFERENCES `products` (`id`),
  CONSTRAINT `fk_sm_warehouse` FOREIGN KEY (`warehouse_id`) REFERENCES `warehouses` (`id`),
  CONSTRAINT `fk_stock_movements_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `chk_sm_quantity` CHECK ((`quantity` > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `customer_warehouse_access` (
  `id` binary(16) NOT NULL,
  `customer_id` binary(16) NOT NULL,
  `warehouse_id` binary(16) NOT NULL,
  `granted_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `granted_by` binary(16) NOT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_customer_warehouse` (`customer_id`,`warehouse_id`),
  KEY `idx_cwa_customer` (`customer_id`),
  KEY `idx_cwa_warehouse` (`warehouse_id`),
  KEY `fk_customer_warehouse_access_company` (`company_id`),
  CONSTRAINT `fk_customer_warehouse_access_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_cwa_customer` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_cwa_warehouse` FOREIGN KEY (`warehouse_id`) REFERENCES `warehouses` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
