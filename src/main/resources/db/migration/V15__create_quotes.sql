CREATE TABLE `quotes` (
  `id` binary(16) NOT NULL,
  `quote_number` varchar(20) NOT NULL,
  `customer_id` binary(16) NOT NULL,
  `customer_name` varchar(200) NOT NULL,
  `customer_rif` varchar(50) NOT NULL,
  `created_by` binary(16) DEFAULT NULL,
  `created_by_name` varchar(200) DEFAULT NULL,
  `status` varchar(20) NOT NULL DEFAULT 'DRAFT',
  `expiry_date` date DEFAULT NULL,
  `notes` varchar(1000) DEFAULT NULL,
  `subtotal` decimal(15,2) NOT NULL DEFAULT '0.00',
  `order_id` binary(16) DEFAULT NULL,
  `order_number` varchar(20) DEFAULT NULL,
  `invoice_id` binary(16) DEFAULT NULL,
  `invoice_number` varchar(20) DEFAULT NULL,
  `cancelled_at` timestamp NULL DEFAULT NULL,
  `cancelled_reason` varchar(500) DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  UNIQUE KEY `quote_number` (`quote_number`),
  KEY `idx_quotes_quote_number` (`quote_number`),
  KEY `idx_quotes_customer_id` (`customer_id`),
  KEY `idx_quotes_created_by` (`created_by`),
  KEY `idx_quotes_status` (`status`),
  KEY `idx_quotes_expiry_date` (`expiry_date`),
  KEY `idx_quotes_created_at` (`created_at`),
  KEY `fk_quotes_company` (`company_id`),
  CONSTRAINT `fk_quotes_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_quotes_customer` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `quote_lines` (
  `id` binary(16) NOT NULL,
  `quote_id` binary(16) NOT NULL,
  `product_id` binary(16) NOT NULL,
  `product_name` varchar(200) NOT NULL,
  `product_code` varchar(50) NOT NULL,
  `quantity` decimal(15,4) NOT NULL,
  `unit_price` decimal(15,2) NOT NULL,
  `line_total` decimal(15,2) NOT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  KEY `idx_quote_lines_quote_id` (`quote_id`),
  KEY `idx_quote_lines_product_id` (`product_id`),
  KEY `fk_quote_lines_company` (`company_id`),
  CONSTRAINT `fk_quote_lines_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_quote_lines_quote` FOREIGN KEY (`quote_id`) REFERENCES `quotes` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `quote_allocations` (
  `id` binary(16) NOT NULL,
  `quote_id` binary(16) NOT NULL,
  `quote_line_id` binary(16) NOT NULL,
  `product_id` binary(16) NOT NULL,
  `warehouse_id` binary(16) NOT NULL,
  `warehouse_name` varchar(200) NOT NULL,
  `allocated_quantity` decimal(15,4) NOT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  KEY `idx_quote_allocations_quote_id` (`quote_id`),
  KEY `idx_quote_allocations_quote_line_id` (`quote_line_id`),
  KEY `idx_quote_allocations_warehouse_id` (`warehouse_id`),
  KEY `idx_quote_allocations_product_id` (`product_id`),
  KEY `fk_quote_allocations_company` (`company_id`),
  CONSTRAINT `fk_quote_allocations_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_quote_allocations_quote` FOREIGN KEY (`quote_id`) REFERENCES `quotes` (`id`),
  CONSTRAINT `fk_quote_allocations_quote_line` FOREIGN KEY (`quote_line_id`) REFERENCES `quote_lines` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `quote_number_sequence` (
  `year` int NOT NULL,
  `next_value` int NOT NULL DEFAULT '1',
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`year`),
  KEY `fk_quote_number_sequence_company` (`company_id`),
  CONSTRAINT `fk_quote_number_sequence_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
