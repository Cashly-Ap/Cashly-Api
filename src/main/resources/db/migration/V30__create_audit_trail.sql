CREATE TABLE `audit_events` (
  `id` binary(16) NOT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  `module` varchar(60) NOT NULL,
  `entity_type` varchar(40) NOT NULL,
  `entity_id` binary(16) NOT NULL,
  `entity_label` varchar(200) NOT NULL,
  `entity_secondary_label` varchar(200) DEFAULT NULL,
  `action` varchar(40) NOT NULL,
  `actor_id` binary(16) DEFAULT NULL,
  `actor_name` varchar(200) NOT NULL,
  `occurred_at` timestamp(6) NOT NULL,
  `description_key` varchar(150) NOT NULL,
  `description_args` json DEFAULT NULL,
  `metadata` json DEFAULT NULL,
  `source` varchar(20) NOT NULL DEFAULT 'WEB',
  PRIMARY KEY (`id`),
  KEY `idx_audit_entity` (`entity_type`,`entity_id`,`occurred_at`),
  KEY `idx_audit_actor` (`actor_id`,`occurred_at`),
  KEY `idx_audit_action` (`module`,`action`,`occurred_at`),
  KEY `idx_audit_company_date` (`company_id`,`occurred_at`),
  KEY `fk_audit_events_company` (`company_id`),
  KEY `fk_audit_events_actor` (`actor_id`),
  CONSTRAINT `fk_audit_events_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_audit_events_actor` FOREIGN KEY (`actor_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
