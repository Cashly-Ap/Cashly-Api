CREATE TABLE `cash_register_movements` (
  `id` binary(16) NOT NULL,
  `register_id` binary(16) NOT NULL,
  `direction` varchar(10) COLLATE utf8mb4_unicode_ci NOT NULL,
  `type` varchar(40) COLLATE utf8mb4_unicode_ci NOT NULL,
  `amount` decimal(15,2) NOT NULL,
  `payment_method_id` binary(16) DEFAULT NULL,
  `payment_method_name` varchar(100) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `description` varchar(500) COLLATE utf8mb4_unicode_ci NOT NULL,
  `source_type` varchar(40) COLLATE utf8mb4_unicode_ci NOT NULL,
  `source_id` binary(16) DEFAULT NULL,
  `created_by` binary(16) DEFAULT NULL,
  `created_by_name` varchar(200) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `occurred_at` datetime NOT NULL,
  `cancelled` boolean NOT NULL DEFAULT FALSE,
  `cancellation_reason` varchar(500) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `cancelled_at` datetime DEFAULT NULL,
  `cancelled_by` binary(16) DEFAULT NULL,
  `cancelled_by_name` varchar(200) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_cash_movement_source` (`source_type`,`source_id`),
  KEY `fk_cash_movement_payment_method` (`payment_method_id`),
  KEY `fk_cash_movement_created_by` (`created_by`),
  KEY `fk_cash_movement_cancelled_by` (`cancelled_by`),
  KEY `idx_cash_movement_register_occurred` (`register_id`,`occurred_at`),
  KEY `idx_cash_movement_type_cancelled` (`type`,`cancelled`),
  KEY `fk_cash_register_movements_company` (`company_id`),
  CONSTRAINT `fk_cash_movement_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_cash_movement_cancelled_by` FOREIGN KEY (`cancelled_by`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_cash_movement_payment_method` FOREIGN KEY (`payment_method_id`) REFERENCES `payment_methods` (`id`),
  CONSTRAINT `fk_cash_movement_register` FOREIGN KEY (`register_id`) REFERENCES `cash_registers` (`id`),
  CONSTRAINT `fk_cash_register_movements_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `chk_cash_movement_amount` CHECK ((`amount` > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
