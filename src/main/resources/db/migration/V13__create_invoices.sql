CREATE TABLE `invoices` (
  `id` binary(16) NOT NULL,
  `invoice_number` varchar(20) NOT NULL,
  `order_id` binary(16) DEFAULT NULL,
  `order_number` varchar(20) DEFAULT NULL,
  `customer_id` binary(16) NOT NULL,
  `customer_name` varchar(200) NOT NULL,
  `customer_rif` varchar(50) NOT NULL,
  `created_by` binary(16) NOT NULL,
  `created_by_name` varchar(200) NOT NULL,
  `status` varchar(30) NOT NULL DEFAULT 'DRAFT',
  `payment_type` varchar(20) DEFAULT NULL,
  `notes` varchar(1000) DEFAULT NULL,
  `subtotal` decimal(15,2) NOT NULL DEFAULT '0.00',
  `cancelled_at` timestamp NULL DEFAULT NULL,
  `cancelled_reason` varchar(500) DEFAULT NULL,
  `returned_total` decimal(15,2) NOT NULL DEFAULT '0.00',
  `return_status` varchar(20) DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `issue_date` date NOT NULL,
  `due_date` date NOT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  UNIQUE KEY `invoice_number` (`invoice_number`),
  KEY `idx_invoices_invoice_number` (`invoice_number`),
  KEY `idx_invoices_order_id` (`order_id`),
  KEY `idx_invoices_customer_id` (`customer_id`),
  KEY `idx_invoices_created_by` (`created_by`),
  KEY `idx_invoices_status` (`status`),
  KEY `idx_invoices_created_at` (`created_at`),
  KEY `fk_invoices_company` (`company_id`),
  CONSTRAINT `fk_invoices_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_invoices_customer` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `invoice_lines` (
  `id` binary(16) NOT NULL,
  `invoice_id` binary(16) NOT NULL,
  `product_id` binary(16) NOT NULL,
  `product_name` varchar(200) NOT NULL,
  `product_code` varchar(50) NOT NULL,
  `quantity` decimal(15,4) NOT NULL,
  `returned_quantity` decimal(15,4) NOT NULL DEFAULT '0.0000',
  `unit_price` decimal(15,2) NOT NULL,
  `line_total` decimal(15,2) NOT NULL,
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`id`),
  KEY `idx_invoice_lines_invoice_id` (`invoice_id`),
  KEY `idx_invoice_lines_product_id` (`product_id`),
  KEY `fk_invoice_lines_company` (`company_id`),
  CONSTRAINT `fk_invoice_lines_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`),
  CONSTRAINT `fk_invoice_lines_invoice` FOREIGN KEY (`invoice_id`) REFERENCES `invoices` (`id`),
  CONSTRAINT `fk_invoice_lines_product` FOREIGN KEY (`product_id`) REFERENCES `products` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `invoice_number_sequence` (
  `year` int NOT NULL,
  `next_value` int NOT NULL DEFAULT '1',
  `company_id` binary(16) NOT NULL DEFAULT 0x92000000000000000000000000000001,
  PRIMARY KEY (`year`),
  KEY `fk_invoice_number_sequence_company` (`company_id`),
  CONSTRAINT `fk_invoice_number_sequence_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
