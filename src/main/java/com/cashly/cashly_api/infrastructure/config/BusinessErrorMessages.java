    static String translate(String source, MessageTranslator translator) {
        String key = EXACT.get(source);
        if (key != null)
            return translator.text(key);
        return PREFIXES.entrySet().stream()
                .filter(entry -> source.startsWith(entry.getKey()))
                .max(java.util.Comparator
                        .comparingInt(entry -> entry.getKey().length()))
                .map(entry -> translator.text(entry.getValue())).orElse(null);
    }
